"""Alembic environment.

The schema metadata is intentionally empty at the bootstrap stage (BE-001 only
proves migrations are upgrade/rollback capable). Real tables land in BE-003
(persistence and consistency foundation). The database URL is read from the
``PYMENTOR_DATABASE_URL`` environment variable; tests pass a file-based URL.
"""

from __future__ import annotations

import os
import sys
from logging.config import fileConfig
from pathlib import Path

# Ensure backend/ is importable so `app.*` resolves when alembic runs from the
# repo root (alembic.ini's prepend_sys_path adds the repo root, not backend/).
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from alembic import context
from sqlalchemy import engine_from_config, pool

# Import Base so Alembic can introspect model metadata for autogenerate.
# Models register themselves on import via the declarative base.
from app.db import Base
from app.models import *  # noqa: F403 (register all models on Base)

config = context.config

if config.config_file_name is not None:
    fileConfig(config.config_file_name)

# BE-002 wires the real declarative metadata; migrations are autogenerated
# from the ORM models.
target_metadata = Base.metadata


def _resolve_url() -> str:
    default = config.get_main_option("sqlalchemy.url") or ""
    return os.environ.get("PYMENTOR_DATABASE_URL", default)


def run_migrations_offline() -> None:
    url = _resolve_url()
    context.configure(
        url=url,
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
    )
    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    db_url = _resolve_url()
    section = config.get_section(config.config_ini_section, {})
    section["sqlalchemy.url"] = db_url
    connectable = engine_from_config(section, prefix="sqlalchemy.", poolclass=pool.NullPool)

    with connectable.connect() as connection:
        context.configure(connection=connection, target_metadata=target_metadata)
        with context.begin_transaction():
            context.run_migrations()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
